import requests, time, pandas as pd

final = pd.read_csv("candidate_drugs.csv")

def pubmed_count(name):
    q = f'"{name}"[Title/Abstract] AND ("oral squamous cell carcinoma"[Title/Abstract] OR "oral cancer"[Title/Abstract])'
    r = requests.get("https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esearch.fcgi",
                     params={"db": "pubmed", "term": q, "retmode": "json"}, timeout=30)
    return int(r.json()["esearchresult"]["count"])

counts = {}
for i, row in final.iterrows():
    if row["drug_name"].startswith("BRD-"):
        continue
    try:
        counts[i] = pubmed_count(row["drug_name"])
    except Exception:
        counts[i] = None
    time.sleep(0.4)

final["pubmed_hits"] = pd.Series(counts)

def decide(row):
    n = row["pubmed_hits"]
    if pd.isna(n):
        return "unknown"
    if n >= 3:
        return "yes"
    if n == 0 and row["approval_status"] != "unknown":
        return "no"
    return "unknown"

final["used_in_oral_cancer"] = final.apply(decide, axis=1)

# evidence file (extra column kept out of the contract file)
final.to_csv("pubmed_evidence.csv", index=False)
