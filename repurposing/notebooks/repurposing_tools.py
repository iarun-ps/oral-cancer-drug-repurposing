records = []

for pert_id in sigcom["Perturbagen"]:

    payload = {
        "filter": {
            "where": {
                "meta": {
                    "fullTextSearch": pert_id
                }
            }
        }
    }

    try:
        response = requests.post(
            api + "/signatures/find",
            json=payload,
            timeout=60
        )
        response.raise_for_status()

        for item in response.json():
            meta = item.get("meta", {})

            # Keep records for the exact compound
            if meta.get("pert_name", "").lower() == pert_id.lower():
                records.append({
                    "Perturbagen": pert_id,
                    "Cell_line": meta.get("cell_line"),
                    "Disease": meta.get("disease"),
                    "Dose": meta.get("pert_dose"),
                    "Treatment_time": meta.get("pert_time"),
                    "Perturbation_type": meta.get("pert_type")
                })

    except Exception as e:
        print("Error:", pert_id, e)

    time.sleep(0.1)

