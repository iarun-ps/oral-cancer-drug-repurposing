import pandas as pd
from rdkit import Chem

ann = pd.read_csv("sigcom_annotated_v2.csv")

# 1. refresh targets / approval / moa using the final drug names
def lookup(name):
    key = str(name).lower()
    if key not in drugs.index:
        return pd.Series({"known_targets": "", "approval_status": "unknown", "moa": None})
    r = drugs.loc[key]
    phase = r["clinical_phase"]
    status = ("unknown" if pd.isna(phase)
              else "approved" if phase == "Launched" else "investigational")
    tg = ";".join(str(r["target"]).split("|")) if pd.notna(r["target"]) else ""
    return pd.Series({"known_targets": tg, "approval_status": status, "moa": r["moa"]})

ann[["known_targets", "approval_status", "moa"]] = ann["drug_name"].apply(lookup)

# 2. standardise SMILES with RDKit
def clean(s):
    if pd.isna(s):
        return None
    m = Chem.MolFromSmiles(str(s))
    return Chem.MolToSmiles(m) if m else None

ann["smiles_clean"] = ann["smiles"].apply(clean)
ann["pubchem_cid"] = pd.to_numeric(ann["pubchem_cid"], errors="coerce").astype("Int64")

# keep the full list for Savin (original ranks)
ann.to_csv("all_ranked_sigcom_final.csv", index=False)

