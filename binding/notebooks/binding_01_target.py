chooser = rdMolStandardize.LargestFragmentChooser()   # drops salts / counter-ions

def prep(smi):
    """Return (ID card, ring skeleton, clean SMILES) or (None, None, None)."""
    m = Chem.MolFromSmiles(str(smi))
    if m is None:
        return None, None, None
    m = chooser.choose(m)
    try:
        key = Chem.MolToInchiKey(m).split("-")[0]        # first block = molecule skeleton, ignores stereo
    except Exception:
        key = None
    try:
        scaf = MurckoScaffold.MurckoScaffoldSmiles(mol=m)
    except Exception:
        scaf = None
    return key, scaf, Chem.MolToSmiles(m)

# --- candidates ---
cinfo = [prep(s) for s in cand["smiles"]]
cand["inchikey14"] = [i[0] for i in cinfo]
cand["scaffold"] = [i[1] for i in cinfo]
cand_keys = set(cand["inchikey14"].dropna())
cand_scaffolds = set(s for s in cand["scaffold"].dropna() if s != "")   # "" = no rings, never match
key2name = dict(zip(cand["inchikey14"], cand["drug_name"]))

