def fp_np(m): return np.array(gen.GetFingerprintAsNumPy(m), dtype=np.uint8)

cand["mol"] = cand["smiles"].map(mol)
Xc = np.vstack([fp_np(m) for m in cand["mol"]])
cand_fps = [gen.GetFingerprint(m) for m in cand["mol"]]

pdb = {"EGFR":"5HG8","PIK3CA":"8EXL","CDK6":"5L2S","MET":"9SXJ",
       "FGFR1":"5EW8","KDR":"3WZD","MAP2K1":"7B7R","HDAC2":"4LY1"}

