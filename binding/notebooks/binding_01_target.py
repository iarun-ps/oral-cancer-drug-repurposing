import os
import numpy as np
import pandas as pd
from rdkit import Chem, RDLogger
from rdkit.Chem import rdFingerprintGenerator
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_squared_error
from scipy.stats import spearmanr
RDLogger.DisableLog("rdApp.*")

train = pd.read_csv("binding/data/train_level2.csv")
held = pd.read_csv("binding/data/heldout_candidates_measured.csv")
gen = rdFingerprintGenerator.GetMorganGenerator(radius=2, fpSize=2048)

def fp(smi):
    m = Chem.MolFromSmiles(str(smi))
    return np.array(gen.GetFingerprintAsNumPy(m), dtype=np.uint8)

def scaffold_split(df, test_frac=0.2):
    """Whole scaffold families go to train or test. Big families fill train first."""
    groups = df.groupby("scaffold").indices
    ordered = sorted(groups.values(), key=len, reverse=True)
    n_train_target = int((1 - test_frac) * len(df))
    tr, te = [], []
    for idx in ordered:
        (tr if len(tr) < n_train_target else te).extend(idx)
    return np.array(tr), np.array(te)

def rmse(y, p): return float(np.sqrt(mean_squared_error(y, p)))
def sp(y, p):   return float(spearmanr(y, p)[0])

rows = []
for t, g in train.groupby("target"):
    g = g.reset_index(drop=True)
    X = np.vstack([fp(s) for s in g["smiles"]]); y = g["pchembl"].values
    tr, te = scaffold_split(g)
    rf = RandomForestRegressor(n_estimators=300, n_jobs=-1, random_state=42)
    rf.fit(X[tr], y[tr])
    p = rf.predict(X[te])
    base = np.full(len(te), y[tr].mean())
    row = {"target": t, "n_train": len(tr), "n_test": len(te),
           "RF_rmse": rmse(y[te], p), "mean_rmse": rmse(y[te], base),
           "RF_spearman": sp(y[te], p)}
    # the 12 known candidates, never seen in training
    h = held[held.target == t]
    if len(h) >= 3:
        ph = rf.predict(np.vstack([fp(s) for s in h["smiles"]]))
        row["n_heldout_drugs"] = len(h); row["heldout_rmse"] = rmse(h["pchembl"], ph)
        row["heldout_spearman"] = sp(h["pchembl"], ph)
    else:
        row["n_heldout_drugs"] = len(h)
    rows.append(row)

res = pd.DataFrame(rows).round(2)
print(res.to_string(index=False))
os.makedirs("binding/results", exist_ok=True)
res.to_csv("binding/results/baseline_metrics.csv", index=False)
print("Saved binding/results/baseline_metrics.csv")

