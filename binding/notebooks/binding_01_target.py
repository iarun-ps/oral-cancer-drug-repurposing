"""Step 2: DepMap check, in plain words

DepMap is a database where researchers switched off each gene, one at a time, in hundreds of cancer cell lines. They recorded whether the cells could still grow. For each target, we look at the head and neck lines and ask: do they die without this gene? If yes, the target really matters for this cancer, which makes a drug that hits it more convincing. This is supporting evidence for Savin’s report, and it takes about 15 minutes.

The simplest route is the DepMap website, because the full data download is very large. For each of the 8 genes, you open depmap.org/portal and search the gene. On its Dependency page, find the head and neck group and write down how strongly those lines depend on it.
"""

import requests, pandas as pd

def top_structures(gene, n=5):
    q = {
        "query": {"type": "group", "logical_operator": "and", "nodes": [
            {"type": "terminal", "service": "text", "parameters": {
                "attribute": "rcsb_entity_source_organism.rcsb_gene_name.value",
                "operator": "exact_match", "value": gene}},
            {"type": "terminal", "service": "text", "parameters": {
                "attribute": "rcsb_entity_source_organism.ncbi_scientific_name",
                "operator": "exact_match", "value": "Homo sapiens"}},
            {"type": "terminal", "service": "text", "parameters": {
                "attribute": "exptl.method",
                "operator": "exact_match", "value": "X-RAY DIFFRACTION"}},
            {"type": "terminal", "service": "text", "parameters": {
                "attribute": "rcsb_entry_info.nonpolymer_entity_count",
                "operator": "greater", "value": 0}},
            {"type": "terminal", "service": "text", "parameters": {
                "attribute": "rcsb_entry_info.resolution_combined",
                "operator": "less", "value": 2.5}},
        ]},
        "return_type": "entry",
        "request_options": {
            "paginate": {"start": 0, "rows": n},
            "sort": [{"sort_by": "rcsb_entry_info.resolution_combined",
                      "direction": "asc"}]},
    }
    r = requests.post("https://search.rcsb.org/rcsbsearch/v2/query", json=q, timeout=60)
    if r.status_code != 200:
        return []
    return [x["identifier"] for x in r.json().get("result_set", [])]

